"""Derive a raised full-arm candidate from frozen reviewed artifacts.

Inputs stay immutable. --base-mesh is generated by export_integrated_arm_preview.py.
Private OEM CAD is used for discrete Boolean checks, never redistributed.
"""
from pathlib import Path
